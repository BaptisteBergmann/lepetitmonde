'use client'

import { useCallback, useEffect, useLayoutEffect, useReducer, useRef, useSyncExternalStore } from 'react'
import { flushSync } from 'react-dom'
import { useTranslations } from 'next-intl'
import { toast } from 'sonner'
import type { Tables } from '@utils/supabase/database.types'
import { INPUT_LIMITS } from '@/utils/input-limits'
import { createTodoItems, deleteTodoItem, toggleTodoItem, updateTodoItem } from '@/utils/actions/todo'
import ChecklistRow, { type ChecklistRowData } from './checklist_row'

const SAVE_DEBOUNCE_MS = 400
// Same cap as the server's MAX_TODO_BATCH (that module is server-only).
const MAX_PASTE_LINES = 100

type Action =
  | { type: 'reset'; rows: ChecklistRowData[]; spareId: string }
  | { type: 'edit'; id: string; title: string; spareId: string }
  | { type: 'insert'; afterId: string | null; rows: ChecklistRowData[]; spareId: string }
  | { type: 'remove'; ids: string[]; spareId: string }
  | { type: 'toggle'; id: string; done: boolean; doneAt: string | null; spareId: string }

const isBlank = (row: ChecklistRowData) => !row.title.trim()

// Invariant: the last unchecked row is empty (the "New item" row), so there is always
// somewhere to type. `spareId` is generated by the event handler so the reducer stays pure.
function withDraft(rows: ChecklistRowData[], spareId: string): ChecklistRowData[] {
  const lastUnchecked = rows.findLast((row) => !row.done)
  if (lastUnchecked && isBlank(lastUnchecked)) return rows
  return [...rows, { id: spareId, title: '', done: false, doneAt: null }]
}

function reducer(rows: ChecklistRowData[], action: Action): ChecklistRowData[] {
  switch (action.type) {
    case 'reset':
      return withDraft(action.rows, action.spareId)
    case 'edit':
      return withDraft(rows.map((row) => (row.id === action.id ? { ...row, title: action.title } : row)), action.spareId)
    case 'insert': {
      const index = action.afterId === null ? rows.length : rows.findIndex((row) => row.id === action.afterId) + 1
      return withDraft([...rows.slice(0, index), ...action.rows, ...rows.slice(index)], action.spareId)
    }
    case 'remove':
      return withDraft(rows.filter((row) => !action.ids.includes(row.id)), action.spareId)
    case 'toggle':
      return withDraft(
        rows.map((row) => (row.id === action.id ? { ...row, done: action.done, doneAt: action.doneAt } : row)),
        action.spareId,
      )
  }
}

function fromServer(items: Tables<'todo_items'>[]): ChecklistRowData[] {
  return items.map((item) => ({ id: item.id, title: item.title, done: item.done, doneAt: item.done_at }))
}

// Strips list markers people paste from other apps: "- ", "* ", "• ", "[ ]", "[x]", "☐".
function parsePaste(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim().replace(/^(?:[-*•☐☑✓]|\[[ xX]?\])\s*/, '').trim())
    .filter(Boolean)
    .map((line) => line.slice(0, INPUT_LIMITS.todoTitle))
}

const subscribeOnline = (callback: () => void) => {
  window.addEventListener('online', callback)
  window.addEventListener('offline', callback)
  return () => {
    window.removeEventListener('online', callback)
    window.removeEventListener('offline', callback)
  }
}

export default function Checklist({ babyId, listId, items }: { babyId: string; listId: string; items: Tables<'todo_items'>[] }) {
  const t = useTranslations('todo')
  const [rows, dispatch] = useReducer(reducer, items, (initial) => withDraft(fromServer(initial), crypto.randomUUID()))
  const online = useSyncExternalStore(subscribeOnline, () => navigator.onLine, () => true)

  const containerRef = useRef<HTMLDivElement>(null)
  const rowsRef = useRef(rows)
  const inputs = useRef(new Map<string, HTMLTextAreaElement>())
  // Ids the server has, or has a create queued for.
  const known = useRef(new Set<string>(items.map((item) => item.id)))
  // Last title the server confirmed, to roll a failed rename back to.
  const saved = useRef(new Map<string, string>(items.map((item) => [item.id, item.title])))
  // Last title queued, so an unchanged blur doesn't write.
  const queued = useRef(new Map<string, string>(items.map((item) => [item.id, item.title])))
  const timers = useRef(new Map<string, ReturnType<typeof setTimeout>>())
  // One promise chain per item id, so create -> rename -> delete run in order.
  const chains = useRef(new Map<string, Promise<void>>())
  const pending = useRef(0)
  const firstSync = useRef(true)

  useLayoutEffect(() => {
    rowsRef.current = rows
  }, [rows])

  // Re-sync from the server only when idle: the refresh after each write would
  // otherwise overwrite what the user is typing.
  useEffect(() => {
    if (firstSync.current) { firstSync.current = false; return }
    if (pending.current > 0 || timers.current.size > 0) return
    if (containerRef.current?.contains(document.activeElement)) return

    known.current = new Set(items.map((item) => item.id))
    saved.current = new Map(items.map((item) => [item.id, item.title]))
    queued.current = new Map(saved.current)
    const draft = rowsRef.current.findLast((row) => !row.done && isBlank(row))
    dispatch({ type: 'reset', rows: fromServer(items), spareId: draft?.id ?? crypto.randomUUID() })
  }, [items])

  const enqueue = useCallback((ids: string[], op: () => Promise<void>, afterId?: string) => {
    pending.current++
    const previous = Promise.all([...ids.map((id) => chains.current.get(id)), afterId ? chains.current.get(afterId) : undefined])
    const next = previous.then(op).catch(() => {}).finally(() => { pending.current-- })
    ids.forEach((id) => chains.current.set(id, next))
  }, [])

  const fail = useCallback((message = t('saveError')) => toast.error(message), [t])

  const focusRow = useCallback((id: string, caret: 'start' | 'end' = 'end') => {
    const element = inputs.current.get(id)
    if (!element) return
    element.focus()
    const position = caret === 'end' ? element.value.length : 0
    element.setSelectionRange(position, position)
  }, [])

  const flushSave = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.delete(id)

    const current = rowsRef.current
    const index = current.findIndex((row) => row.id === id)
    if (index === -1) return
    const title = current[index].title.trim()
    if (!title) return

    if (!known.current.has(id)) {
      // Placed after the nearest row the server already has (or will have).
      const afterId = current.slice(0, index).findLast((row) => known.current.has(row.id))?.id
      known.current.add(id)
      queued.current.set(id, title)
      enqueue([id], async () => {
        try {
          await createTodoItems(babyId, listId, [{ id, title }], afterId)
          saved.current.set(id, title)
        } catch (err) {
          console.error(err)
          known.current.delete(id)
          dispatch({ type: 'remove', ids: [id], spareId: crypto.randomUUID() })
          fail()
        }
      }, afterId)
      return
    }

    if (queued.current.get(id) === title) return
    queued.current.set(id, title)
    enqueue([id], async () => {
      if (!known.current.has(id)) return
      try {
        await updateTodoItem(babyId, id, { title })
        saved.current.set(id, title)
      } catch (err) {
        console.error(err)
        const previous = saved.current.get(id) ?? title
        queued.current.set(id, previous)
        dispatch({ type: 'edit', id, title: previous, spareId: crypto.randomUUID() })
        fail()
      }
    })
  }, [babyId, listId, enqueue, fail])

  const scheduleSave = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.set(id, setTimeout(() => flushSave(id), SAVE_DEBOUNCE_MS))
  }, [flushSave])

  const flushAll = useCallback(() => {
    for (const id of [...timers.current.keys()]) flushSave(id)
  }, [flushSave])

  // iOS can suspend the page right after the last keystroke: flush before it does.
  useEffect(() => {
    const onHide = () => { if (document.visibilityState === 'hidden') flushAll() }
    document.addEventListener('visibilitychange', onHide)
    window.addEventListener('pagehide', flushAll)
    const pendingTimers = timers.current
    return () => {
      document.removeEventListener('visibilitychange', onHide)
      window.removeEventListener('pagehide', flushAll)
      // Leaving the page: don't lose the debounced title.
      flushAll()
      pendingTimers.forEach((timer) => clearTimeout(timer))
    }
  }, [flushAll])

  const removeRow = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.delete(id)
    dispatch({ type: 'remove', ids: [id], spareId: crypto.randomUUID() })
    if (known.current.has(id)) {
      known.current.delete(id)
      enqueue([id], async () => {
        try {
          await deleteTodoItem(babyId, id)
        } catch (err) {
          console.error(err)
          fail()
        }
      })
    }
  }, [babyId, enqueue, fail])

  const handleChange = (id: string, title: string) => {
    dispatch({ type: 'edit', id, title, spareId: crypto.randomUUID() })
    if (title.trim()) scheduleSave(id)
  }

  const handleToggle = (id: string) => {
    const row = rowsRef.current.find((r) => r.id === id)
    if (!row || isBlank(row)) return
    const done = !row.done
    dispatch({ type: 'toggle', id, done, doneAt: done ? new Date().toISOString() : null, spareId: crypto.randomUUID() })
    // The row may still be waiting for its debounced create.
    flushSave(id)
    enqueue([id], async () => {
      if (!known.current.has(id)) return
      try {
        await toggleTodoItem(babyId, id, done)
      } catch (err) {
        console.error(err)
        dispatch({ type: 'toggle', id, done: !done, doneAt: null, spareId: crypto.randomUUID() })
        fail()
      }
    })
  }

  const handleKeyDown = (event: React.KeyboardEvent<HTMLTextAreaElement>, row: ChecklistRowData) => {
    if (event.nativeEvent.isComposing) return
    const unchecked = rowsRef.current.filter((r) => !r.done)
    const index = unchecked.findIndex((r) => r.id === row.id)

    if (event.key === 'Enter') {
      event.preventDefault()
      const element = event.currentTarget
      const value = element.value
      if (!value.trim()) return
      // Caret at the very start would push all the text into the new row: treat it as "end".
      const caret = element.selectionStart > 0 ? element.selectionStart : value.length
      const before = value.slice(0, caret).trimEnd()
      const after = value.slice(caret).trimStart()
      const next = unchecked[index + 1]
      const nextIsDraft = next && isBlank(next) && next.id === unchecked[unchecked.length - 1].id

      // Focus moves in this same key event: after an await, iOS Safari closes the keyboard.
      if (nextIsDraft && !after) {
        flushSave(row.id)
        focusRow(next.id)
        return
      }
      const newId = crypto.randomUUID()
      flushSync(() => {
        dispatch({ type: 'edit', id: row.id, title: before, spareId: crypto.randomUUID() })
        dispatch({ type: 'insert', afterId: row.id, rows: [{ id: newId, title: after, done: false, doneAt: null }], spareId: crypto.randomUUID() })
      })
      focusRow(newId, 'start')
      flushSave(row.id)
      if (after) flushSave(newId)
      return
    }

    if (event.key === 'Backspace' && event.currentTarget.value === '') {
      const previous = unchecked[index - 1]
      if (!previous) return
      event.preventDefault()
      const isDraft = index === unchecked.length - 1
      if (isDraft) {
        // The trailing row stays; only the caret moves up.
        focusRow(previous.id)
        return
      }
      flushSync(() => removeRow(row.id))
      focusRow(previous.id)
    }
  }

  const handlePaste = (event: React.ClipboardEvent<HTMLTextAreaElement>, row: ChecklistRowData) => {
    const text = event.clipboardData.getData('text')
    if (!/\r?\n/.test(text)) return
    event.preventDefault()

    let lines = parsePaste(text)
    if (lines.length === 0) return
    if (lines.length > MAX_PASTE_LINES) {
      lines = lines.slice(0, MAX_PASTE_LINES)
      toast.info(t('pasteTruncated'))
    }

    const element = event.currentTarget
    const merged = (element.value.slice(0, element.selectionStart) + lines[0] + element.value.slice(element.selectionEnd))
      .slice(0, INPUT_LIMITS.todoTitle)
    const created = lines.slice(1).map((title) => ({ id: crypto.randomUUID(), title, done: false, doneAt: null }))

    flushSync(() => {
      dispatch({ type: 'edit', id: row.id, title: merged, spareId: crypto.randomUUID() })
      if (created.length) dispatch({ type: 'insert', afterId: row.id, rows: created, spareId: crypto.randomUUID() })
    })
    if (created.length) focusRow(created[created.length - 1].id)

    flushSave(row.id)
    if (!created.length) return
    const ids = created.map((item) => item.id)
    ids.forEach((id) => { known.current.add(id); queued.current.set(id, created.find((c) => c.id === id)!.title) })
    enqueue(ids, async () => {
      try {
        await createTodoItems(babyId, listId, created.map(({ id, title }) => ({ id, title })), row.id)
        created.forEach(({ id, title }) => saved.current.set(id, title))
      } catch (err) {
        console.error(err)
        ids.forEach((id) => known.current.delete(id))
        dispatch({ type: 'remove', ids, spareId: crypto.randomUUID() })
        fail()
      }
    }, row.id)
  }

  const handleBlur = (id: string) => {
    flushSave(id)
    const unchecked = rowsRef.current.filter((r) => !r.done)
    const row = rowsRef.current.find((r) => r.id === id)
    // An emptied item goes away, except the trailing row that always stays.
    if (row && !row.done && isBlank(row) && unchecked[unchecked.length - 1]?.id !== id) removeRow(id)
  }

  const register = useCallback((id: string, element: HTMLTextAreaElement | null) => {
    if (element) inputs.current.set(id, element)
    else inputs.current.delete(id)
  }, [])

  const unchecked = rows.filter((row) => !row.done)
  const done = rows.filter((row) => row.done).sort((a, b) => (b.doneAt ?? '').localeCompare(a.doneAt ?? ''))
  const draftId = unchecked[unchecked.length - 1]?.id
  const hasItems = rows.some((row) => !isBlank(row))

  const renderRow = (row: ChecklistRowData) => (
    <ChecklistRow
      key={row.id}
      row={row}
      isDraft={row.id === draftId}
      onToggle={handleToggle}
      onChange={handleChange}
      onKeyDown={handleKeyDown}
      onPaste={handlePaste}
      onBlur={handleBlur}
      register={register}
    />
  )

  return (
    <div ref={containerRef} className="space-y-3">
      {!online && (
        <p role="status" className="text-sm text-landing-muted">{t('offline')}</p>
      )}
      <div className="overflow-hidden rounded-2xl border border-landing-border bg-landing-surface">
        {unchecked.map(renderRow)}
      </div>
      {!hasItems && <p className="text-sm text-landing-muted">{t('emptyHint')}</p>}
      {done.length > 0 && (
        <div className="overflow-hidden rounded-2xl border border-landing-border bg-landing-surface">
          {done.map(renderRow)}
        </div>
      )}
    </div>
  )
}
