'use client'

import { useCallback, useEffect, useId, useLayoutEffect, useReducer, useRef, useState, useSyncExternalStore } from 'react'
import { flushSync } from 'react-dom'
import { useTranslations } from 'next-intl'
import { useRouter } from 'next/navigation'
import { ChevronRight } from 'lucide-react'
import { toast } from 'sonner'
import { useConfirm } from '@/components/confirm_provider'
import { cn } from '@utils/utils'
import type { Tables } from '@utils/supabase/database.types'
import { INPUT_LIMITS } from '@/utils/input-limits'
import { clearDoneTodoItems, createTodoItems, deleteTodoItem, toggleTodoItem, updateTodoItem } from '@/utils/actions/todo'
import ChecklistRow, { type ChecklistRowData } from './checklist_row'
import { mergeRows } from './merge_rows'
import { useTodoLive } from './use_todo_live'

const SAVE_DEBOUNCE_MS = 400
// Undo window: a checked item stays in place this long before sinking into Done.
const SINK_DELAY_MS = 600
const LEAVE_MS = 200
// A row stays protected from server snapshots this long after our last write to it
// settled: a refresh that started before the write can land after it.
const GRACE_MS = 2000
const doneOpenKey = (listId: string) => `todo-done-open:${listId}`
// Same cap as the server's MAX_TODO_BATCH (that module is server-only).
const MAX_PASTE_LINES = 100

type Action =
  | { type: 'merge'; rows: ChecklistRowData[]; spareId: string }
  | { type: 'edit'; id: string; title: string; spareId: string }
  | { type: 'insert'; afterId: string | null; rows: ChecklistRowData[]; spareId: string }
  | { type: 'remove'; ids: string[]; spareId: string }
  | { type: 'toggle'; id: string; done: boolean; doneAt: string | null; spareId: string }

const isBlank = (row: ChecklistRowData) => !row.title.trim()

// Invariant: the last unchecked row is empty (the "New item" row), so there is always
// somewhere to type. `spareId` is generated by the event handler so the reducer stays pure.
function withDraft(rows: ChecklistRowData[], spareId: string): ChecklistRowData[] {
  const lastUnchecked = rows.findLast((row) => !row.done)
  if (lastUnchecked && isBlank(lastUnchecked)) return rows
  return [...rows, { id: spareId, title: '', done: false, doneAt: null }]
}

function reducer(rows: ChecklistRowData[], action: Action): ChecklistRowData[] {
  switch (action.type) {
    case 'merge':
      return withDraft(action.rows, action.spareId)
    case 'edit':
      return withDraft(rows.map((row) => (row.id === action.id ? { ...row, title: action.title } : row)), action.spareId)
    case 'insert': {
      const index = action.afterId === null ? rows.length : rows.findIndex((row) => row.id === action.afterId) + 1
      return withDraft([...rows.slice(0, index), ...action.rows, ...rows.slice(index)], action.spareId)
    }
    case 'remove':
      return withDraft(rows.filter((row) => !action.ids.includes(row.id)), action.spareId)
    case 'toggle':
      return withDraft(
        rows.map((row) => (row.id === action.id ? { ...row, done: action.done, doneAt: action.doneAt } : row)),
        action.spareId,
      )
  }
}

function fromServer(items: Tables<'todo_items'>[]): ChecklistRowData[] {
  return items.map((item) => ({ id: item.id, title: item.title, done: item.done, doneAt: item.done_at }))
}

// The server caps titles in UTF-16 units, so clip to that without cutting an emoji
// (surrogate pair) in half and leaving a lone surrogate behind.
function clip(text: string): string {
  const clipped = text.slice(0, INPUT_LIMITS.todoTitle)
  const last = clipped.charCodeAt(clipped.length - 1)
  return last >= 0xd800 && last <= 0xdbff ? clipped.slice(0, -1) : clipped
}

// Strips list markers people paste from other apps: "- ", "* ", "• ", "[ ]", "[x]", "☐".
function parsePaste(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim().replace(/^(?:[-*•☐☑✓]|\[[ xX]?\])\s*/, '').trim())
    .filter(Boolean)
    .map(clip)
}

const doneOpenListeners = new Set<() => void>()
const subscribeDoneOpen = (callback: () => void) => {
  doneOpenListeners.add(callback)
  return () => { doneOpenListeners.delete(callback) }
}

const subscribeOnline = (callback: () => void) => {
  window.addEventListener('online', callback)
  window.addEventListener('offline', callback)
  return () => {
    window.removeEventListener('online', callback)
    window.removeEventListener('offline', callback)
  }
}

export default function Checklist({ babyId, listId, items }: { babyId: string; listId: string; items: Tables<'todo_items'>[] }) {
  const t = useTranslations('todo')
  const router = useRouter()
  const confirmAction = useConfirm()
  const doneListId = useId()
  const [rows, dispatch] = useReducer(reducer, items, (initial) => withDraft(fromServer(initial), crypto.randomUUID()))
  // Checked rows still shown among the unchecked ones (undo window), and the subset
  // already collapsing.
  const [sinking, setSinking] = useState<ReadonlySet<string>>(new Set())
  const [leaving, setLeaving] = useState<ReadonlySet<string>>(new Set())
  // Per list, remembered on this device. Server snapshot is closed, so hydration matches.
  const doneOpen = useSyncExternalStore(subscribeDoneOpen, () => localStorage.getItem(doneOpenKey(listId)) === '1', () => false)
  const [announcement, setAnnouncement] = useState('')
  const sinkTimers = useRef(new Map<string, ReturnType<typeof setTimeout>[]>())
  const online = useSyncExternalStore(subscribeOnline, () => navigator.onLine, () => true)

  const containerRef = useRef<HTMLDivElement>(null)
  const rowsRef = useRef(rows)
  const inputs = useRef(new Map<string, HTMLTextAreaElement>())
  // Ids the server has, or has a create queued for.
  const known = useRef(new Set<string>(items.map((item) => item.id)))
  // Last title the server confirmed, to roll a failed rename back to.
  const saved = useRef(new Map<string, string>(items.map((item) => [item.id, item.title])))
  // Last title queued, so an unchanged blur doesn't write.
  const queued = useRef(new Map<string, string>(items.map((item) => [item.id, item.title])))
  const timers = useRef(new Map<string, ReturnType<typeof setTimeout>>())
  // One promise chain per item id, so create -> rename -> delete run in order.
  const chains = useRef(new Map<string, Promise<void>>())
  const pending = useRef(0)
  const firstSync = useRef(true)
  // Ops in flight per id, and when each id's last write settled (see GRACE_MS).
  const inflight = useRef(new Map<string, number>())
  const graceUntil = useRef(new Map<string, number>())
  // Focused rows another device deleted: kept on screen until blur.
  const remoteDeleted = useRef(new Set<string>())
  // Rows the last merge held back, and the latest server snapshot to retry against.
  const deferredIds = useRef<ReadonlySet<string>>(new Set())
  const itemsRef = useRef(items)

  const scheduleRefresh = useTodoLive(babyId, {
    isBusy: () => pending.current > 0 || timers.current.size > 0,
  })

  useLayoutEffect(() => {
    rowsRef.current = rows
  }, [rows])

  const toggleDoneOpen = () => {
    localStorage.setItem(doneOpenKey(listId), doneOpen ? '0' : '1')
    doneOpenListeners.forEach((listener) => listener())
  }

  const focusRow = useCallback((id: string, caret: 'start' | 'end' = 'end') => {
    const element = inputs.current.get(id)
    if (!element) return
    element.focus()
    const position = caret === 'end' ? element.value.length : 0
    element.setSelectionRange(position, position)
  }, [])

  const stopSinking = useCallback((id: string) => {
    sinkTimers.current.get(id)?.forEach(clearTimeout)
    sinkTimers.current.delete(id)
    const without = (set: ReadonlySet<string>) => {
      const next = new Set(set)
      next.delete(id)
      return next
    }
    setSinking(without)
    setLeaving(without)
  }, [])

  // Once the row leaves the unchecked list its checkbox unmounts (or hides), which would
  // drop keyboard focus to <body>: hand it to the next unchecked row, or the trailing row.
  const settleSink = useCallback((id: string, title: string, announce: boolean) => {
    const hadFocus = (document.activeElement as HTMLElement | null)?.dataset.checkboxId === id
    const current = rowsRef.current
    const target = current.slice(current.findIndex((row) => row.id === id) + 1).find((row) => !row.done && row.title.trim())
    flushSync(() => stopSinking(id))
    if (announce) setAnnouncement(t('movedToDone', { title }))
    if (!hadFocus) return
    const draft = current.findLast((row) => !row.done)
    if (target && target.id !== draft?.id) {
      containerRef.current?.querySelector<HTMLElement>(`[data-checkbox-id="${target.id}"]`)?.focus()
    } else if (draft) {
      focusRow(draft.id)
    }
  }, [stopSinking, focusRow, t])

  // Remote ticks play the same animation but stay silent for screen readers.
  const startSinking = useCallback((id: string, title: string, announce = true) => {
    setSinking((set) => new Set(set).add(id))
    const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches
    const leave = setTimeout(() => {
      if (reduceMotion) {
        settleSink(id, title, announce)
        return
      }
      setLeaving((set) => new Set(set).add(id))
      const settle = setTimeout(() => settleSink(id, title, announce), LEAVE_MS)
      sinkTimers.current.set(id, [settle])
    }, SINK_DELAY_MS)
    sinkTimers.current.set(id, [leave])
  }, [settleSink])

  useEffect(() => {
    const timersByRow = sinkTimers.current
    return () => timersByRow.forEach((list) => list.forEach(clearTimeout))
  }, [])

  // Reconciles the screen with the latest server snapshot row by row: protected rows
  // (focused, unsaved, in flight, recently written) keep their local state.
  const runMerge = useCallback(() => {
    const now = Date.now()
    const active = document.activeElement
    let focusedId: string | null = null
    for (const [id, element] of inputs.current) {
      if (element === active) { focusedId = id; break }
    }
    const lockedIds = new Set<string>([...timers.current.keys(), ...inflight.current.keys()])
    for (const [id, until] of graceUntil.current) {
      if (until > now) lockedIds.add(id)
      else graceUntil.current.delete(id)
    }

    const result = mergeRows(rowsRef.current, fromServer(itemsRef.current), {
      known: known.current,
      lockedIds,
      focusedId,
      focusInside: !!containerRef.current?.contains(active),
    })

    for (const [id, title] of result.adopted) {
      known.current.add(id)
      saved.current.set(id, title)
      queued.current.set(id, title)
    }
    for (const id of result.dropped) {
      known.current.delete(id)
      saved.current.delete(id)
      queued.current.delete(id)
      stopSinking(id)
    }
    for (const id of result.remoteDeleted) {
      known.current.delete(id)
      remoteDeleted.current.add(id)
    }
    deferredIds.current = result.deferred
    if (!result.changed) return

    const titles = new Map(result.rows.map((row) => [row.id, row.title]))
    result.remoteChecked.forEach((id) => startSinking(id, titles.get(id) ?? '', false))
    result.remoteUnchecked.forEach(stopSinking)
    const draft = rowsRef.current.findLast((row) => !row.done && isBlank(row))
    dispatch({ type: 'merge', rows: result.rows, spareId: draft?.id ?? crypto.randomUUID() })
  }, [stopSinking, startSinking])

  useEffect(() => {
    itemsRef.current = items
    if (firstSync.current) { firstSync.current = false; return }
    runMerge()
  }, [items, runMerge])

  const enqueue = useCallback((ids: string[], op: () => Promise<void>, afterId?: string) => {
    pending.current++
    ids.forEach((id) => inflight.current.set(id, (inflight.current.get(id) ?? 0) + 1))
    const previous = Promise.all([...ids.map((id) => chains.current.get(id)), afterId ? chains.current.get(afterId) : undefined])
    const next = previous.then(op).catch(() => {}).finally(() => {
      pending.current--
      const settledAt = Date.now()
      for (const id of ids) {
        const left = (inflight.current.get(id) ?? 1) - 1
        if (left > 0) inflight.current.set(id, left)
        else inflight.current.delete(id)
        graceUntil.current.set(id, settledAt + GRACE_MS)
      }
      // Rows held back only because of the grace window are re-read once it ends: that
      // snapshot is newer than our write, so the state converges. Merging the stale
      // one again here could undo the write.
      setTimeout(() => {
        if (ids.some((id) => deferredIds.current.has(id))) scheduleRefresh()
      }, GRACE_MS + 50)
    })
    ids.forEach((id) => chains.current.set(id, next))
  }, [scheduleRefresh])

  const fail = useCallback((message = t('saveError')) => toast.error(message), [t])

  // The server no longer has the row (another device deleted it while we edited): bring
  // it back under the same id, so the user's edit wins over the remote delete.
  const recreateRow = useCallback(async (id: string, title: string, done: boolean) => {
    const current = rowsRef.current
    const index = current.findIndex((row) => row.id === id)
    const afterId = current.slice(0, Math.max(index, 0)).findLast((row) => row.id !== id && known.current.has(row.id))?.id
    known.current.add(id)
    remoteDeleted.current.delete(id)
    try {
      await createTodoItems(babyId, listId, [{ id, title }], afterId)
      saved.current.set(id, title)
      queued.current.set(id, title)
      if (done) await toggleTodoItem(babyId, id, true)
    } catch (err) {
      known.current.delete(id)
      throw err
    }
  }, [babyId, listId])

  const flushSave = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.delete(id)

    const current = rowsRef.current
    const index = current.findIndex((row) => row.id === id)
    if (index === -1) return
    const title = current[index].title.trim()
    if (!title) return

    if (!known.current.has(id)) {
      // Placed after the nearest row the server already has (or will have).
      const afterId = current.slice(0, index).findLast((row) => known.current.has(row.id))?.id
      known.current.add(id)
      remoteDeleted.current.delete(id)
      queued.current.set(id, title)
      enqueue([id], async () => {
        try {
          await createTodoItems(babyId, listId, [{ id, title }], afterId)
          saved.current.set(id, title)
        } catch (err) {
          console.error(err)
          known.current.delete(id)
          dispatch({ type: 'remove', ids: [id], spareId: crypto.randomUUID() })
          fail()
        }
      }, afterId)
      return
    }

    if (queued.current.get(id) === title) return
    queued.current.set(id, title)
    enqueue([id], async () => {
      if (!known.current.has(id)) return
      try {
        const matched = await updateTodoItem(babyId, id, { title })
        if (matched) saved.current.set(id, title)
        else await recreateRow(id, title, rowsRef.current.find((row) => row.id === id)?.done ?? false)
      } catch (err) {
        console.error(err)
        const previous = saved.current.get(id) ?? title
        queued.current.set(id, previous)
        dispatch({ type: 'edit', id, title: previous, spareId: crypto.randomUUID() })
        fail()
      }
    })
  }, [babyId, listId, enqueue, fail, recreateRow])

  const scheduleSave = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.set(id, setTimeout(() => flushSave(id), SAVE_DEBOUNCE_MS))
  }, [flushSave])

  const flushAll = useCallback(() => {
    for (const id of [...timers.current.keys()]) flushSave(id)
  }, [flushSave])

  // iOS can suspend the page right after the last keystroke: flush before it does.
  useEffect(() => {
    const onHide = () => { if (document.visibilityState === 'hidden') flushAll() }
    document.addEventListener('visibilitychange', onHide)
    window.addEventListener('pagehide', flushAll)
    const pendingTimers = timers.current
    return () => {
      document.removeEventListener('visibilitychange', onHide)
      window.removeEventListener('pagehide', flushAll)
      // Leaving the page: don't lose the debounced title.
      flushAll()
      pendingTimers.forEach((timer) => clearTimeout(timer))
    }
  }, [flushAll])

  const removeRow = useCallback((id: string) => {
    const timer = timers.current.get(id)
    if (timer) clearTimeout(timer)
    timers.current.delete(id)
    dispatch({ type: 'remove', ids: [id], spareId: crypto.randomUUID() })
    if (known.current.has(id)) {
      known.current.delete(id)
      enqueue([id], async () => {
        try {
          await deleteTodoItem(babyId, id)
        } catch (err) {
          console.error(err)
          fail()
        }
      })
    }
  }, [babyId, enqueue, fail])

  const handleChange = (id: string, title: string) => {
    dispatch({ type: 'edit', id, title, spareId: crypto.randomUUID() })
    if (title.trim()) scheduleSave(id)
  }

  const handleToggle = (id: string) => {
    const row = rowsRef.current.find((r) => r.id === id)
    if (!row || isBlank(row)) return
    const done = !row.done
    const previousDoneAt = row.doneAt
    dispatch({ type: 'toggle', id, done, doneAt: done ? new Date().toISOString() : null, spareId: crypto.randomUUID() })
    if (done) startSinking(id, row.title)
    else stopSinking(id)
    // The row may still be waiting for its debounced create.
    flushSave(id)
    enqueue([id], async () => {
      if (!known.current.has(id)) return
      try {
        const matched = await toggleTodoItem(babyId, id, done)
        if (!matched) await recreateRow(id, row.title.trim(), done)
      } catch (err) {
        console.error(err)
        dispatch({ type: 'toggle', id, done: !done, doneAt: previousDoneAt, spareId: crypto.randomUUID() })
        if (done) stopSinking(id)
        fail()
      }
    })
  }

  const handleKeyDown = (event: React.KeyboardEvent<HTMLTextAreaElement>, row: ChecklistRowData) => {
    if (event.nativeEvent.isComposing || row.done) return
    const unchecked = rowsRef.current.filter((r) => !r.done)
    const index = unchecked.findIndex((r) => r.id === row.id)

    if (event.key === 'Enter') {
      event.preventDefault()
      const element = event.currentTarget
      const value = element.value
      if (!value.trim()) return
      // Caret at the very start would push all the text into the new row: treat it as "end".
      const caret = element.selectionStart > 0 ? element.selectionStart : value.length
      const before = value.slice(0, caret).trimEnd()
      const after = value.slice(caret).trimStart()
      const next = unchecked[index + 1]
      const nextIsDraft = next && isBlank(next) && next.id === unchecked[unchecked.length - 1].id

      // Focus moves in this same key event: after an await, iOS Safari closes the keyboard.
      if (nextIsDraft && !after) {
        flushSave(row.id)
        focusRow(next.id)
        return
      }
      const newId = crypto.randomUUID()
      flushSync(() => {
        dispatch({ type: 'edit', id: row.id, title: before, spareId: crypto.randomUUID() })
        dispatch({ type: 'insert', afterId: row.id, rows: [{ id: newId, title: after, done: false, doneAt: null }], spareId: crypto.randomUUID() })
      })
      focusRow(newId, 'start')
      flushSave(row.id)
      if (after) flushSave(newId)
      return
    }

    if (event.key === 'Backspace' && event.currentTarget.value === '') {
      const previous = unchecked[index - 1]
      if (!previous) return
      event.preventDefault()
      const isDraft = index === unchecked.length - 1
      if (isDraft) {
        // The trailing row stays; only the caret moves up.
        focusRow(previous.id)
        return
      }
      flushSync(() => removeRow(row.id))
      focusRow(previous.id)
    }
  }

  const handlePaste = (event: React.ClipboardEvent<HTMLTextAreaElement>, row: ChecklistRowData) => {
    if (row.done) return
    const text = event.clipboardData.getData('text')
    if (!/\r?\n/.test(text)) return
    event.preventDefault()

    let lines = parsePaste(text)
    if (lines.length === 0) return
    if (lines.length > MAX_PASTE_LINES) {
      lines = lines.slice(0, MAX_PASTE_LINES)
      toast.info(t('pasteTruncated'))
    }

    const element = event.currentTarget
    const merged = clip(element.value.slice(0, element.selectionStart) + lines[0] + element.value.slice(element.selectionEnd))
    const created = lines.slice(1).map((title) => ({ id: crypto.randomUUID(), title, done: false, doneAt: null }))

    flushSync(() => {
      dispatch({ type: 'edit', id: row.id, title: merged, spareId: crypto.randomUUID() })
      if (created.length) dispatch({ type: 'insert', afterId: row.id, rows: created, spareId: crypto.randomUUID() })
    })
    if (created.length) focusRow(created[created.length - 1].id)

    flushSave(row.id)
    if (!created.length) return
    const ids = created.map((item) => item.id)
    ids.forEach((id) => { known.current.add(id); queued.current.set(id, created.find((c) => c.id === id)!.title) })
    enqueue(ids, async () => {
      try {
        await createTodoItems(babyId, listId, created.map(({ id, title }) => ({ id, title })), row.id)
        created.forEach(({ id, title }) => saved.current.set(id, title))
      } catch (err) {
        console.error(err)
        ids.forEach((id) => known.current.delete(id))
        dispatch({ type: 'remove', ids, spareId: crypto.randomUUID() })
        fail()
      }
    }, row.id)
  }

  const handleClearDone = async () => {
    const doneRows = rowsRef.current.filter((row) => row.done)
    if (doneRows.length === 0) return
    const confirmed = await confirmAction({
      title: t('clearDoneConfirm', { count: doneRows.length }),
      confirmLabel: t('clearDone'),
      destructive: true,
    })
    if (!confirmed) return

    const ids = doneRows.map((row) => row.id)
    ids.forEach((id) => { stopSinking(id); known.current.delete(id) })
    dispatch({ type: 'remove', ids, spareId: crypto.randomUUID() })
    const draft = rowsRef.current.findLast((row) => !row.done)
    if (draft) focusRow(draft.id)
    enqueue(ids, async () => {
      try {
        await clearDoneTodoItems(babyId, listId)
      } catch (err) {
        console.error(err)
        toast.error(t('clearDoneError'))
        // Local state dropped rows the server still has: re-read them.
        router.refresh()
      }
    })
  }

  const handleBlur = (id: string) => {
    if (remoteDeleted.current.has(id)) {
      const gone = rowsRef.current.find((r) => r.id === id)
      // Untouched: just let it go, no write. Edited: the create path below brings it
      // back under the same id (the user's edit wins).
      if (gone && gone.title.trim() === saved.current.get(id)) {
        remoteDeleted.current.delete(id)
        saved.current.delete(id)
        queued.current.delete(id)
        removeRow(id)
        return
      }
    }
    flushSave(id)
    // Deferred remote changes to this row can apply now that focus has left it.
    setTimeout(runMerge, 0)
    const unchecked = rowsRef.current.filter((r) => !r.done)
    const row = rowsRef.current.find((r) => r.id === id)
    // An emptied item goes away, except the trailing row that always stays.
    if (row && !row.done && isBlank(row) && unchecked[unchecked.length - 1]?.id !== id) removeRow(id)
  }

  const register = useCallback((id: string, element: HTMLTextAreaElement | null) => {
    if (element) inputs.current.set(id, element)
    else inputs.current.delete(id)
  }, [])

  const unchecked = rows.filter((row) => !row.done || sinking.has(row.id))
  const done = rows
    .filter((row) => row.done && !sinking.has(row.id))
    .sort((a, b) => (b.doneAt ?? '').localeCompare(a.doneAt ?? ''))
  const draftId = rows.findLast((row) => !row.done)?.id
  const hasItems = rows.some((row) => !isBlank(row))

  const renderRow = (row: ChecklistRowData) => (
    <ChecklistRow
      key={row.id}
      row={row}
      isDraft={row.id === draftId}
      leaving={leaving.has(row.id)}
      onToggle={handleToggle}
      onChange={handleChange}
      onKeyDown={handleKeyDown}
      onPaste={handlePaste}
      onBlur={handleBlur}
      register={register}
    />
  )

  return (
    <div ref={containerRef} className="space-y-3">
      {!online && (
        <p role="status" className="text-sm text-landing-muted">{t('offline')}</p>
      )}
      <div className="overflow-hidden rounded-2xl border border-landing-border bg-landing-surface">
        {unchecked.map(renderRow)}
      </div>
      {!hasItems && <p className="text-sm text-landing-muted">{t('emptyHint')}</p>}
      {done.length > 0 && (
        <div>
          <div className="flex min-h-11 items-center justify-between">
            <button
              type="button"
              aria-expanded={doneOpen}
              aria-controls={doneListId}
              onClick={toggleDoneOpen}
              className="flex min-h-11 cursor-pointer items-center gap-1 text-sm font-medium text-landing-foreground"
            >
              <ChevronRight
                aria-hidden
                className={cn('size-4 motion-safe:transition-transform motion-safe:duration-200', doneOpen && 'rotate-90')}
              />
              {t('doneSection', { count: done.length })}
            </button>
            <button
              type="button"
              onClick={handleClearDone}
              aria-label={t('clearDoneAria', { count: done.length })}
              className="min-h-11 cursor-pointer px-2 text-sm text-landing-muted hover:text-landing-foreground"
            >
              {t('clearDone')}
            </button>
          </div>
          <div
            id={doneListId}
            hidden={!doneOpen}
            className="overflow-hidden rounded-2xl border border-landing-border bg-landing-surface"
          >
            {done.map(renderRow)}
          </div>
        </div>
      )}
      <div aria-live="polite" className="sr-only">{announcement}</div>
    </div>
  )
}
